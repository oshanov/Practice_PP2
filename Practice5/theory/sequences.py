# \d - matches any digit
# \D - mathces any NON digit
# \w - matches any char
# \W - matches any NON char
# \s - Returns a match where the string contains a white space character
# \S - Returns a match where the string DOES NOT contain a white space character
# \A - synonim to ^ - Returns a match if the specified characters are at the beginning of the string
# \Z - synonim to $ - Returns a match if the specified characters are at the end of the string
# \b - Returns a match where the specified characters are at the beginning or at the end of a word(Границы слов - ищет только отдельное слово)
# \B - Returns a match where the specified characters are present, but NOT at the beginning (or at the end) of a word